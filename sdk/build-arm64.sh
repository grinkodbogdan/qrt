#!/bin/sh
# sdk/build-arm64.sh [OUT] - the SDK for 64-bit ARM programs (the Mi A1): musl 1.2.6
# for AArch64 and the qrt-a64-cc compiler driver.
#
#   OUT/sysroot/usr/include, usr/lib   musl, Linux's UAPI headers
#   OUT/bin/qrt-a64-cc                 clang: static PIE programs for QRT on ARM
#
# Programs use Linux's AArch64 system calls; the kernel's Linux layer runs them (src/user,
# src/arch/arm64/uentry.c).  Needs clang, ld.lld, llvm-ar and an AArch64 libgcc
# (gcc-aarch64-linux-gnu) for the compiler runtime.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/.." && pwd)
out=${1:-$root/build/sdk-arm64}
mkdir -p "$out/src" "$out/bin"
out=$(cd "$out" && pwd)
sys="$out/sysroot"
CC="clang --target=aarch64-linux-musl"

rm -rf "$out/src/musl"
tar -xzf "$here/musl-1.2.6.tar.gz" -C "$out/src"
( cd "$out/src/musl" &&
  CC="$CC" AR=llvm-ar RANLIB=llvm-ranlib ./configure --target=aarch64 --prefix=/usr --syslibdir=/lib \
      --disable-shared CFLAGS="-O2 -g0" >/dev/null &&
  make -j"$(nproc)" >/dev/null &&
  make DESTDIR="$sys" install >/dev/null )
for d in linux asm-generic mtd drm sound video rdma misc scsi; do cp -r "/usr/include/$d" "$sys/usr/include/"; done
cp -r /usr/aarch64-linux-gnu/include/asm "$sys/usr/include/asm"
gcclib=$(dirname "$(aarch64-linux-gnu-gcc -print-libgcc-file-name)")
cp "$gcclib/libgcc.a" "$sys/usr/lib/libgcc.a"
cp "$gcclib/crtbeginS.o" "$gcclib/crtendS.o" "$gcclib/crtbegin.o" "$gcclib/crtend.o" "$gcclib/crtbeginT.o" "$sys/usr/lib/"
mkdir -p "$out/nogcc"                     # clang must not take the host's (glibc) AArch64 GCC start files
llvm-ar rcs "$sys/usr/lib/libgcc_eh.a"
cat > "$out/bin/qrt-a64-cc" <<EOS
#!/bin/sh
# qrt-a64-cc: clang for 64-bit ARM programs on QRT (static PIE, musl)
link="-static-pie"
for a in "\$@"; do [ "\$a" = "-r" ] && link=""; done       # a partial link (-r) is not a program
exec clang --target=aarch64-linux-musl --sysroot="$sys" --gcc-toolchain="$out/nogcc" -nostdlibinc -isystem "$sys/usr/include" \\
    \$link -fPIE -fuse-ld=lld --rtlib=libgcc -L"$sys/usr/lib" "\$@"
EOS
chmod +x "$out/bin/qrt-a64-cc"
# CMake: C programs and libraries (C++ once sdk/build-arm64-cxx.sh has built libc++)
cat > "$out/qrt-a64.cmake" <<EOS
# CMake toolchain file for 64-bit ARM programs on QRT (generated by sdk/build-arm64.sh)
set(CMAKE_SYSTEM_NAME Linux)
set(CMAKE_SYSTEM_PROCESSOR aarch64)
set(QRT ON)
set(CMAKE_SYSROOT "$sys")
set(CMAKE_C_COMPILER clang-20)
set(CMAKE_CXX_COMPILER clang++-20)
set(CMAKE_ASM_COMPILER clang-20)
set(CMAKE_C_COMPILER_TARGET aarch64-linux-musl)
set(CMAKE_CXX_COMPILER_TARGET aarch64-linux-musl)
set(CMAKE_ASM_COMPILER_TARGET aarch64-linux-musl)
set(CMAKE_AR /usr/bin/llvm-ar-20)
set(CMAKE_RANLIB /usr/bin/llvm-ranlib-20)
set(CMAKE_C_FLAGS_INIT "-D__QRT__ -fPIE --gcc-toolchain=$out/nogcc")
set(CMAKE_CXX_FLAGS_INIT "-D__QRT__ -fPIE --gcc-toolchain=$out/nogcc -stdlib=libc++")
set(CMAKE_POSITION_INDEPENDENT_CODE ON)
set(CMAKE_EXE_LINKER_FLAGS_INIT "$(if [ -f "$out/.cxxstamp" ]; then echo "-static-pie -fuse-ld=lld -rtlib=compiler-rt -unwindlib=libunwind -stdlib=libc++"; else echo "-static-pie -fuse-ld=lld --rtlib=libgcc"; fi)")
set(CMAKE_FIND_ROOT_PATH "$sys")
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
set(BUILD_SHARED_LIBS OFF CACHE BOOL "static only")
set(ENV{PKG_CONFIG_LIBDIR} "$sys/usr/lib/pkgconfig:$sys/usr/share/pkgconfig")
set(ENV{PKG_CONFIG_SYSROOT_DIR} "$sys")
EOS
# libqrt: QRT's windows and input (the same calls as the x86-64 SDK's, sdk/libqrt)
python3 "$here/libqrt/genfont.py" "$root/assets/Inter-Regular.ttf" "$out/src/qrt_font.c"
cp "$here/libqrt/qrt.h" "$sys/usr/include/qrt.h"
"$out/bin/qrt-a64-cc" -O2 -Wall -c "$here/libqrt/qrt.c" -o "$out/src/qrt.o"
"$out/bin/qrt-a64-cc" -O2 -c "$out/src/qrt_font.c" -o "$out/src/qrt_font.o"
llvm-ar rcs "$sys/usr/lib/libqrt.a" "$out/src/qrt.o" "$out/src/qrt_font.o"
touch "$out/.stamp"
echo "QRT SDK for ARM in $out (qrt-a64-cc: $out/bin/qrt-a64-cc)"
