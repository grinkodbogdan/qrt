/* Host test for src/drivers/hidmouse.c: report descriptors of real pointer
 * devices, and the reports they send.
 *   - the HID 1.11 specification's example mouse (Appendix E.10): 3 buttons,
 *     relative 8-bit X/Y, plus a wheel;
 *   - a gaming/wireless-receiver style mouse: report ID 2, 16 buttons, 12-bit
 *     X/Y packed across bytes, wheel and AC Pan, after a keyboard report;
 *   - QEMU's usb-tablet (hw/usb/dev-hid.c): absolute 0..32767 X/Y;
 *   - the boot protocol fallback.
 * Build/run: make check */
#include <stdio.h>
#include <string.h>
typedef unsigned char u8; typedef unsigned short u16; typedef unsigned int u32; typedef unsigned long long u64;
typedef signed char i8; typedef short i16; typedef int i32; typedef long long i64;
#define ARRAY_LEN(a) (sizeof(a) / sizeof((a)[0]))
#define CLAMP(v, lo, hi) ((v) < (lo) ? (lo) : (v) > (hi) ? (hi) : (v))
#define HID_HOST_TEST 1
#include "../src/drivers/hidmouse.c"

static int fails;
#define CHECK(c, ...) do { if (!(c)) { fails++; printf("FAIL: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static const u8 spec_mouse[] = {
    0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x09, 0x01, 0xa1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02,
    0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7f, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06,
    0xc0, 0xc0,
};

static const u8 receiver[] = {
    /* report 1: a keyboard (must be skipped) */
    0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x85, 0x01, 0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x26, 0xff, 0x00, 0x19, 0x00, 0x2a, 0xff, 0x00, 0x81, 0x00, 0xc0,
    /* report 2: the mouse */
    0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x85, 0x02, 0x09, 0x01, 0xa1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x10, 0x15, 0x00, 0x25, 0x01, 0x95, 0x10, 0x75, 0x01, 0x81, 0x02,
    0x05, 0x01, 0x16, 0x01, 0xf8, 0x26, 0xff, 0x07, 0x75, 0x0c, 0x95, 0x02, 0x09, 0x30, 0x09, 0x31, 0x81, 0x06,
    0x15, 0x81, 0x25, 0x7f, 0x75, 0x08, 0x95, 0x01, 0x09, 0x38, 0x81, 0x06,
    0x05, 0x0c, 0x0a, 0x38, 0x02, 0x95, 0x01, 0x81, 0x06,
    0xc0, 0xc0,
};

static const u8 qemu_tablet[] = {
    0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x09, 0x01, 0xa1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02,
    0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x00, 0x26, 0xff, 0x7f, 0x35, 0x00, 0x46, 0xff, 0x7f,
    0x75, 0x10, 0x95, 0x02, 0x81, 0x02,
    0x05, 0x01, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7f, 0x35, 0x00, 0x45, 0x00, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06,
    0xc0, 0xc0,
};

int main(void) {
    hidmouse_t m;
    mouse_report_t r;

    CHECK(hm_parse(&m, spec_mouse, sizeof spec_mouse), "spec mouse not recognised");
    CHECK(m.nbuttons == 3 && m.x.rel && m.wheel.present && !m.uses_ids, "spec mouse fields");
    u8 r1[] = { 0x05, 0xfb, 0x07, 0xff };                      /* left+middle, dx -5, dy 7, wheel -1 */
    CHECK(hm_decode(&m, r1, sizeof r1, &r) && !r.abs && r.x == -5 && r.y == 7 && r.wheel == -1 && r.buttons == 5,
          "spec report: %d %d %d %x", r.x, r.y, r.wheel, r.buttons);

    CHECK(hm_parse(&m, receiver, sizeof receiver), "receiver mouse not recognised");
    CHECK(m.uses_ids && m.report_id == 2 && m.nbuttons == 8 && m.x.bits == 12 && m.pan.present, "receiver fields: id %d, %d buttons, x %d bits",
          m.report_id, m.nbuttons, m.x.bits);
    /* X = -300 (0xed4), Y = +1000 (0x3e8), packed 12+12 bits little-endian; wheel +2, pan -1; button 2 */
    u32 xy = (0xed4u) | (0x3e8u << 12);
    u8 r2[] = { 0x02, 0x02, 0x00, (u8)xy, (u8)(xy >> 8), (u8)(xy >> 16), 0x02, 0xff };
    CHECK(hm_decode(&m, r2, sizeof r2, &r) && r.x == -300 && r.y == 1000 && r.wheel == 2 && r.pan == -1 && r.buttons == 2,
          "receiver report: %d %d %d %d %x", r.x, r.y, r.wheel, r.pan, r.buttons);
    u8 kb[] = { 0x01, 0, 0, 4, 0, 0, 0, 0, 0 };
    CHECK(!hm_decode(&m, kb, sizeof kb, &r), "a keyboard report decoded as a mouse");

    CHECK(hm_parse(&m, qemu_tablet, sizeof qemu_tablet), "QEMU tablet not recognised");
    u8 r3[] = { 0x01, 0xff, 0x3f, 0xff, 0x7f, 0x00 };          /* left, x 16383, y 32767 */
    CHECK(hm_decode(&m, r3, sizeof r3, &r) && r.abs && r.buttons == 1 && r.x >= 32766 && r.x <= 32768 && r.y == 65535,
          "tablet report: abs %d %d %d %x", r.abs, r.x, r.y, r.buttons);

    hm_boot(&m);
    u8 r4[] = { 0x02, 0x10, 0xf0 };
    CHECK(hm_decode(&m, r4, sizeof r4, &r) && r.x == 16 && r.y == -16 && r.buttons == 2 && r.wheel == 0, "boot report");

    if (fails) { printf("test_mouse: %d failure(s)\n", fails); return 1; }
    printf("test_mouse: HID mice (relative, report IDs, 12-bit axes, wheel, pan), tablets and boot protocol pass\n");
    return 0;
}
